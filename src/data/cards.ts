function pickRandom<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateNewCard(existingCards: Set<string>): string {
  let attempts = 0;
  while (attempts < 50) {
    const templateIndex = Math.floor(Math.random() * CARD_TEMPLATES.length);
    let card = "";

    switch (templateIndex) {
      case 0:
        card = `Quem seria capaz de ${pickRandom(ACOES_ABSURDAS)}?`;
        break;
      case 1:
        card = `Quem ${pickRandom(ACOES_EMBARACOSAS)} sem sentir vergonha nenhuma?`;
        break;
      case 2:
        card = `Se ${pickRandom(SITUACOES_HIPOTETICAS)}, quem seria o primeiro a ${pickRandom(REACOES)}?`;
        break;
      case 3:
        card = `Quem desse grupo ${pickRandom(CARACTERISTICAS)}?`;
        break;
      case 4:
        card = `Quem teria mais chance de ${pickRandom(SITUACOES_RIDICULAS)}?`;
        break;
    }

    if (card && !existingCards.has(card)) {
      return card;
    }
    attempts++;
  }
  // Fallback
  return `Quem seria capaz de ${pickRandom(ACOES_ABSURDAS)}?`;
}
